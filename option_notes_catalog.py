def _clean_note(txt: str) -> str:
    s = str(txt or "").strip()
    if not s:
        return ""
    s = s.replace("——", "：").replace("—", "：")
    s = re.sub(r"\s+", " ", s).strip()
    return s


def _explain_phonemic_trap(opt: str, answer: str) -> str:
    """Detect exact hiragana phonemic trap between distractor `opt` and correct reading `answer`."""
    if not (_HIRAGANA_ONLY_RE.match(opt) and _HIRAGANA_ONLY_RE.match(answer)):
        return ""
    if opt == answer:
        return ""
    # 1. Exact single dakuten flip
    if len(opt) == len(answer):
        diffs = [(i, answer[i], opt[i]) for i in range(len(opt)) if answer[i] != opt[i]]
        if len(diffs) == 1:
            _, a_ch, o_ch = diffs[0]
            if _DAKUTEN_PAIRS.get(a_ch) == o_ch:
                return f"清浊音陷阱：正确读音这里是「{a_ch}」，误读成了「{o_ch}」。"
    # 2. Extra / missing sokuon っ
    if opt.replace("っ", "") == answer and "っ" in opt:
        return f"多加促音陷阱：正确读音「{answer}」中没有促音「っ」。"
    if answer.replace("っ", "") == opt and "っ" in answer:
        return f"漏读促音陷阱：正确读音「{answer}」必须保留促音「っ」。"
    # 3. Extra / missing long vowel う / ー
    if len(opt) == len(answer) + 1 and ("う" in opt or "ー" in opt):
        for i, ch in enumerate(opt):
            if ch in ("う", "ー") and opt[:i] + opt[i + 1 :] == answer:
                return f"多加长音陷阱：正确读音是短音「{answer}」，这里多加了「{ch}」。"
    if len(answer) == len(opt) + 1 and ("う" in answer or "ー" in answer):
        for i, ch in enumerate(answer):
            if ch in ("う", "ー") and answer[:i] + answer[i + 1 :] == opt:
                return f"漏读长音陷阱：正确读音「{answer}」中不能省掉长音「{ch}」。"
    return f"误读干扰项：正确读音应为「{answer}」，注意不要与「{opt}」混淆。"


def _explain_morph_fallback(opt: str, answer: str, subject: str = "") -> str:
    """Smart morphological & syntactic fallback for any unseen or auto-authored distractor."""
    if not opt:
        return ""
    if _HIRAGANA_ONLY_RE.match(opt) and _HIRAGANA_ONLY_RE.match(answer) and subject in ("語彙", "词汇", "vocab"):
        p_note = _explain_phonemic_trap(opt, answer)
        if p_note:
            return p_note
    if opt.endswith(("させられた", "させられて", "させられる", "させられます")):
        return f"使役受身形（「被迫…」），与本题主语和正解「{answer}」的语态不符。"
    if opt.endswith(("させた", "させて", "させる", "させます")):
        return f"使役形（「让别人…」），与本题动作发出者和正解「{answer}」不符。"
    if opt.endswith(("られた", "られて", "られる", "られます", "された", "されて", "される", "されます")):
        return f"受身或可能变形，与本题语态或句意不符，正解应为「{answer}」。"
    if opt.endswith(("ておく", "ておいた", "ておきます", "ておいて")):
        return "表「提前做好准备」，与本题语境不符。"
    if opt.endswith(("てしまう", "てしまった", "てしまいます", "てしまって")):
        return "表「彻底完成或遗憾结果」，与本题语境不符。"
    if opt.endswith(("ている", "ていた", "ています", "ていました")):
        return "表动作持续或进行状态，与本题时态或语态不符。"
    if opt.endswith(("ない", "なかった", "ません", "ませんでした")):
        return f"否定形式，与本题前后呼应或句意不符，正解应为「{answer}」。"
    return f"词义、接续或语态与本题语境不符，此处应选「{answer}」。"


def ensure_complete_opt_notes(
    card_id: str,
    choices: list[str],
    answer: str,
    existing_notes: dict[str, str] | None,
    *,
    subject: str = "",
    point_key: str = "",
    why_line: str = "",
    form_line: str = "",
    is_listening: bool = False,
) -> dict[str, str]:
    """
    Guarantee that 100% of options in `choices` have a non-empty, plain-Chinese,
    zero-em-dash explanation in the returned dict.
    """
    out: dict[str, str] = {}
    for k, v in (existing_notes or {}).items():
        cleaned = _clean_note(v)
        if cleaned:
            out[str(k).strip()] = cleaned

    card_ovr = CARD_OPTION_OVERRIDES.get(str(card_id or "").strip(), {})
    ans = str(answer or "").strip()

    for raw_opt in (choices or []):
        opt = str(raw_opt or "").strip()
        if not opt:
            continue
        if out.get(opt):
            continue
        # 1) Card-specific tailored override
        if opt in card_ovr:
            out[opt] = _clean_note(card_ovr[opt])
            continue
        # 2) Correct answer fallback to why_line / form_line
        if opt == ans:
            ans_txt = _clean_note(why_line or form_line or OPTION_NOTE_CATALOG.get(opt, ""))
            if ans_txt:
                out[opt] = ans_txt
                continue
        # 3) Curated N3 catalog entry
        if opt in OPTION_NOTE_CATALOG:
            out[opt] = _clean_note(OPTION_NOTE_CATALOG[opt])
            continue
        # 4) Phonemic / morphological smart analyzer
        out[opt] = _clean_note(_explain_morph_fallback(opt, ans, subject=subject))

    return out
