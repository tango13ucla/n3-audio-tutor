def _load_qq_short_stinger(gdr) -> "np.ndarray | None":
    """Extract a crisp 2.35s authentic 《锵锵》 opening stinger from audio/qq_real_intro.wav."""
    if np is None:
        return None
    for cand in (
        os.path.join(BASE_DIR, "audio", "qq_real_intro.wav"),
        os.path.join(BASE_DIR, "audio", "qq_sting.mp3"),
    ):
        if os.path.exists(cand) and os.path.getsize(cand) > 4000:
            try:
                pcm = gdr.decode_to_pcm_f32(cand, trim_speech=False)
                if pcm is None or len(pcm) < int(gdr.SR * 0.8):
                    continue
                target_n = min(len(pcm), int(gdr.SR * 2.45))
                clip = pcm[:target_n].copy()
                # Smooth fade-in (40ms) and gentle broadcast fade-out under WenTao's entrance (last 0.95s)
                fi = min(int(gdr.SR * 0.04), len(clip) // 4)
                fo = min(int(gdr.SR * 0.95), len(clip) // 2)
                if fi > 4:
                    clip[:fi] *= np.linspace(0.0, 1.0, fi, dtype=np.float32)
                if fo > 8:
                    clip[-fo:] *= np.linspace(1.0, 0.0, fo, dtype=np.float32) ** 1.4
                # Normalize stinger softly to -16 dB relative to voice so it feels classy in the car
                rms = float(np.sqrt(np.mean(clip * clip) + 1e-12))
                if rms > 1e-5:
                    clip *= min(0.22 / rms, 1.6)
                return clip.astype(np.float32)
            except Exception:
                continue
    return None


def _render_mp3_64k(mixer, out_mp3: str, sr: int = 24000) -> float:
    """Render stereo studio timeline to crisp 64kbps voice MP3 (~1MB per 2.2 min episode)."""
    total_n = max(1, mixer.max_written)
    audio = mixer.buf[:total_n].copy()
    rng = np.random.default_rng(20261127)
    edge_n = min(int(sr * 0.8), total_n // 4)
    w_l = rng.standard_normal(total_n).astype(np.float32)
    w_r = rng.standard_normal(total_n).astype(np.float32)
    r_l = (w_l + np.roll(w_l, 1) + np.roll(w_l, 2)) * 0.00034
    r_r = (w_r + np.roll(w_r, 1) + np.roll(w_r, 2)) * 0.00034
    room = np.empty((total_n, 2), dtype=np.float32)
    room[:, 0] = 0.78 * r_l + 0.22 * r_r
    room[:, 1] = 0.78 * r_r + 0.22 * r_l
    if edge_n > 10:
        room[:edge_n] *= np.linspace(0.0, 1.0, edge_n, dtype=np.float32)[:, None]
        room[-edge_n:] *= np.linspace(1.0, 0.0, edge_n, dtype=np.float32)[:, None]
    audio += room

    # Normalize speech loudness cleanly for car listening (consistent RMS ~0.165, safe soft peak ceiling)
    rms = float(np.sqrt(np.mean(audio * audio) + 1e-12))
    if rms > 1e-5:
        gain = min(0.165 / rms, 1.85)
        audio = audio * gain
    audio = np.where(np.abs(audio) > 0.85, np.tanh(audio * 1.05) * 0.89, audio)
    pcm16 = np.clip(audio * 32767.0, -32768, 32767).astype(np.int16)

    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tf:
        wav_p = tf.name
    try:
        with wave.open(wav_p, "wb") as wf:
            wf.setnchannels(2)
            wf.setsampwidth(2)
            wf.setframerate(sr)
            wf.writeframes(pcm16.tobytes())
        subprocess.run(
            [
                "ffmpeg", "-y", "-loglevel", "error",
                "-i", wav_p,
                "-vn", "-ar", str(sr), "-ac", "2", "-b:a", "64k", "-c:a", "libmp3lame",
                out_mp3,
            ],
            check=True,
        )
    finally:
        if os.path.exists(wav_p):
            os.remove(wav_p)
    return total_n / float(sr)


_KANA_RE = re.compile(r"[\u3040-\u30ff]")
_QUOTED_JA_RE = re.compile(r"「([^「」]{1,42})」")


def _protect_quoted_ja_terms(text: str) -> str:
    """Wrap any quoted Japanese term containing kana (including Kanji+Kana like 「小さいながらも」,
    「知りながらも」, 「残念ながらも」, 「初心者ながらも」, 「鈴木様をご存じですか」) into an atomic
    `{{carrier|ja}}` swap token so Kanji is NEVER chopped off and misread in Chinese!"""
    if "{{" in text:
        return text

    def _repl(m: re.Match) -> str:
        inner = m.group(1).strip()
        if not inner or not _KANA_RE.search(inner):
            return m.group(0)
        # Keep morphology labels like 「た形」「て形」「ます形」「ない形」 natural (kana JA + 形 ZH)
        if inner.endswith("形") and len(inner) <= 5 and not re.search(r"[\u4e00-\u9fff]", inner[:-1]):
            kana_stem = inner[:-1]
            return f"「{{{{词|{kana_stem}}}}}形」"
        # Pick a smooth Mandarin carrier roughly matching syllable cadence
        n = len(inner)
        if n == 1:
            carrier = "字"
        elif n <= 3:
            carrier = "这词"
        elif n <= 6:
            carrier = "这个词"
        elif n <= 10:
            carrier = "这个说法"
        else:
            carrier = "这句日语"
        return f"「{{{{{carrier}|{inner}}}}}」"

    out = _QUOTED_JA_RE.sub(_repl, text)
    # Also protect unquoted morphology words like 动词ます形 / 去掉ます
    out = re.sub(r"(?<!\|)(ます|ない|た|て)形", r"{{词|\1}}形", out)
    out = re.sub(r"去掉(ます)", r"去掉{{词|\1}}", out)
    out = re.sub(r"去(ます)", r"去{{词|\1}}", out)
    return out


async def synth_one_grammar_pod(
    pod: dict,
    gdr,
    voice_map: dict,
    stinger_pcm,
    sem: asyncio.Semaphore,
    out_mp3: str,
    dry_test: bool = False,
) -> float:
    """Synthesize a single 2-3 min broadcast-grade 《锵锵语法微课》 episode."""
    raw_turns = []
    prev_txt = ""
    for idx_t, (k, v) in enumerate(pod["turns"]):
        if k in ("PAUSE", "LATCH"):
            raw_turns.append((k, v))
            continue
        clean_v = re.sub(r"\*+", "", str(v)).strip()
        # Skip redundant 1-term W_JA echo immediately after Turn 1 already pronounced that exact kana phrase
        if idx_t == 1 and k.endswith("_JA") and len(clean_v.rstrip("。！？")) <= 12:
            bare = clean_v.rstrip("。！？")
            if bare and bare in prev_txt:
                continue
        if k in ("W", "D", "X"):
            clean_v = _protect_quoted_ja_terms(clean_v)
        raw_turns.append((k, clean_v))
        prev_txt = str(v)
    events = gdr.turns_to_expanded_events(raw_turns)

    if dry_test:
        chars = sum(len(str(v)) for k, v in raw_turns if k not in ("PAUSE", "LATCH"))
        return max(95.0, chars * 0.195 + 2.5)

    tmpdir = tempfile.mkdtemp(prefix=f"gpod_{pod['gid']}_")
    try:
        unique_turns: dict[tuple[str, str], str] = {}
        mixed_keys: set[tuple[str, str]] = set()
        for k, val in events:
            if k not in ("PAUSE", "LATCH"):
                txt_s = str(val)
                key = (k, txt_s)
                if key not in unique_turns:
                    thash = hashlib.sha256(f"{k}:{txt_s}".encode("utf-8")).hexdigest()[:12]
                    unique_turns[key] = os.path.join(tmpdir, f"t_{thash}.mp3")
                    if gdr.SWAP_TOKEN_RE.search(txt_s):
                        mixed_keys.add(key)

        # Stage 1: inline Japanese swaps if any
        unique_inline_ja: dict[tuple[str, str], str] = {}
        for k, txt_s in mixed_keys:
            for m in gdr.SWAP_TOKEN_RE.finditer(txt_s):
                ja_w = m.group(2).strip()
                jkey = (k, ja_w)
                if ja_w and jkey not in unique_inline_ja:
                    jhash = hashlib.sha256(f"ija:{k}:{ja_w}".encode("utf-8")).hexdigest()[:12]
                    unique_inline_ja[jkey] = os.path.join(tmpdir, f"ija_{jhash}.mp3")

        ja_pcm_map: dict[tuple[str, str], np.ndarray] = {}
        if unique_inline_ja:
            await asyncio.gather(
                *(
                    gdr.synth_turn(f"{k.split('_')[0]}_JA_INLINE", gdr.inline_ja_voice_cfg(k, voice_map, ja_w), ja_w, jp, sem)
                    for (k, ja_w), jp in unique_inline_ja.items()
                )
            )
            for jkey, jp in unique_inline_ja.items():
                if os.path.exists(jp) and os.path.getsize(jp) > 0:
                    raw = gdr.apply_host_vocal_timbre(gdr.decode_to_pcm_f32(jp, trim_speech=False), jkey[0])
                    is_tiny = len(jkey[1]) <= 2
                    arr = gdr.tight_trim_pcm(
                        raw,
                        thresh_db=-42.0 if is_tiny else -34.0,
                        pad_head_ms=14.0 if is_tiny else 6.0,
                        pad_tail_ms=18.0 if is_tiny else 8.0,
                    )
                    if len(arr) > 0:
                        ja_pcm_map[jkey] = arr

        # Stage 2: synthesize plain & mixed turns in parallel
        plain_items = [(key, p) for key, p in unique_turns.items() if key not in mixed_keys]
        mixed_items = [(key, p) for key, p in unique_turns.items() if key in mixed_keys]
        carrier_specs = {key: gdr.build_carrier_and_spans(key[1]) for key, _ in mixed_items}

        plain_tasks = [
            gdr.synth_turn(k, voice_map.get(k, voice_map["W"]), txt, raw_p, sem)
            for (k, txt), raw_p in plain_items
        ]
        mixed_tasks = [
            gdr.synth_edge_with_boundaries(
                k, voice_map.get(k, voice_map["W"]), carrier_specs[(k, txt)][0], raw_p, sem, target_spans=carrier_specs[(k, txt)][1]
            )
            for (k, txt), raw_p in mixed_items
        ]
        plain_results, mixed_res_list = await asyncio.gather(
            asyncio.gather(*plain_tasks),
            asyncio.gather(*mixed_tasks),
        )
        _ = plain_results

        clip_pcm: dict[tuple[str, str], np.ndarray] = {}

        def _decode_plain(item):
            key, raw_p = item
            if os.path.exists(raw_p) and os.path.getsize(raw_p) > 0:
                return key, gdr.decode_to_pcm_f32(raw_p, trim_speech=True, spk_key=key[0])
            return key, None

        def _splice_mixed(args):
            key, raw_p, res = args
            if res is None:
                return key, None
            bnds, carrier_zh, target_spans = res
            arr = gdr.splice_mixed_swap_pcm(key[0], carrier_zh, target_spans, raw_p, bnds or [], ja_pcm_map)
            return key, arr

        with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
            for key, arr in pool.map(_decode_plain, plain_items):
                if arr is not None and len(arr) > 0:
                    clip_pcm[key] = arr
            mixed_fallbacks: list[tuple[str, str]] = []
            for key, arr in pool.map(
                _splice_mixed,
                [(key, raw_p, res) for (key, raw_p), res in zip(mixed_items, mixed_res_list)],
            ):
                if arr is not None and len(arr) > 0:
                    clip_pcm[key] = arr
                else:
                    mixed_fallbacks.append(key)

        if mixed_fallbacks:
            fb_arrs = await asyncio.gather(
                *(
                    gdr.fallback_tight_stitch_mixed(k, voice_map.get(k, voice_map["W"]), txt, tmpdir, sem, ja_pcm_map)
                    for k, txt in mixed_fallbacks
                )
            )
            for key, arr in zip(mixed_fallbacks, fb_arrs):
                if arr is not None and len(arr) > 0:
                    clip_pcm[key] = arr

        # Stage 3: Mix into stereo StudioTimelineMixer with gentle 《锵锵》 opening stinger
        mixer = gdr.StudioTimelineMixer(est_minutes=4.0, stereo=True)
        if stinger_pcm is not None and len(stinger_pcm) > 0:
            mixer.place_at(0.0, stinger_pcm, gain=0.82, pan=0.0, room_glue=False)
            # WenTao comes in smoothly right as the stinger begins fading out (1.45s)
            mixer.advance(1.45)

        pending_latch = 0.0
        prev_was_ja = False
        for k, val in events:
            if k == "PAUSE":
                mixer.advance(float(val))
                pending_latch = 0.0
            elif k == "LATCH":
                pending_latch = float(val)
            else:
                key = (k, str(val))
                arr = clip_pcm.get(key)
                if arr is None or len(arr) == 0:
                    pending_latch = 0.0
                    continue
                is_ja_sent = k.endswith("_JA")
                # Cognitive language-switch breath (0.24s) before standalone Japanese example sentences
                if is_ja_sent and not prev_was_ja:
                    mixer.advance(0.24)
                    pending_latch = 0.0
                pan = gdr.host_pan_for(k)
                gain = gdr.gear_gain_linear(k)
                mixer.append_clip(arr, gain=gain, crossfade_sec=pending_latch, pan=pan, room_glue=True)
                pending_latch = 0.0
                if is_ja_sent:
                    mixer.advance(0.26)
                prev_was_ja = is_ja_sent

        mixer.advance(0.45)
        dur = _render_mp3_64k(mixer, out_mp3, sr=gdr.SR)
        return dur
    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)


