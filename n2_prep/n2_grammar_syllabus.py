def get_day_new_grammar(day: int) -> list[dict]:
    """Return brand-new N2 grammar items scheduled for study day `day` (1..90)."""
    return [g for g in N2_GRAMMAR_SYLLABUS if g["day"] == day]


def get_day_callback_grammar(day: int) -> list[dict]:
    """Return previously learned N2 grammar items due for natural spaced echo on `day`."""
    due = []
    for g in N2_GRAMMAR_SYLLABUS:
        delta = day - g["day"]
        if delta in (1, 5, 14):
            stage = {1: "next_day_echo", 5: "week1_reunion", 14: "week2_lock"}[delta]
            due.append({**g, "callback_delta": delta, "callback_stage": stage})
    return due


