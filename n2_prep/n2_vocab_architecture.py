def build_n2_daily_vocab_plan(day: int, travel_mode: bool = False) -> dict:
    """Calculate the 3-track daily vocab target for Intake Day `day` (1..90) or Sprint Day (91..115)."""
    if day > 90:
        return {
            "day": day,
            "phase": "march_mock_sprint",
            "new_total": 0,
            "tracks": {"hard_bone": 0, "reading_trap": 0, "fast_screen": 0},
            "due_reviews": 55,
            "est_minutes": 15,
            "note": "3月冲刺期停学新词，全火力清空红黄薄弱词与真题阅读高频词。",
        }
    if travel_mode or (8 <= day <= 34):
        tracks = {"hard_bone": 8, "reading_trap": 7, "fast_screen": 5}
        reviews = 28
        est_min = 13
        phase = "travel_steady_floor"
    elif day >= 35:
        tracks = {"hard_bone": 14, "reading_trap": 11, "fast_screen": 9}
        reviews = 42
        est_min = 19
        phase = "home_full_speed"
    else:
        tracks = {"hard_bone": 10, "reading_trap": 9, "fast_screen": 6}
        reviews = 20
        est_min = 15
        phase = "week1_bridge"
    return {
        "day": day,
        "phase": phase,
        "new_total": sum(tracks.values()),
        "tracks": tracks,
        "due_reviews": reviews,
        "est_minutes": est_min,
    }


def simulate_90_day_vocab_coverage() -> dict:
    """Verify exact cumulative vocabulary screened/learned across Days 1..90."""
    totals = {"hard_bone": 0, "reading_trap": 0, "fast_screen": 0}
    for d in range(1, 91):
        p = build_n2_daily_vocab_plan(d)
        for k, v in p["tracks"].items():
            totals[k] += v
    totals["grand_total"] = sum(totals.values())
    return totals


