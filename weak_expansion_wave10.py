def _q_turns_from_prompt(voice: str, prompt: str) -> list[tuple]:
    parts = prompt.split("（　　）")
    if len(parts) == 2:
        left, right = parts[0].strip(), parts[1].strip()
        turns: list[tuple] = []
        if left:
            turns.append((voice, left))
        if right and right not in ("。", "？", "！"):
            if turns:
                turns.append(("PAUSE", 0.32))
            turns.append((voice, right))
        return turns or [(voice, prompt)]
    return [(voice, prompt)]


