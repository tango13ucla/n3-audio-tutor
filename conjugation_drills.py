def build_conj_audio_turns(drill: dict) -> dict[str, list]:
    """Return bilingual studio TTS turn specs (ask, teach, model) for one conjugation drill."""
    base_k = str(drill["base_kana"]).strip(" 。") + "。"
    ask_zh = str(drill["ask_zh"]).strip()
    target_k = str(drill["target_kana"]).strip(" 。") + "。"
    chunk_k = str(drill["chunk_kana"]).strip(" 。") + "。"
    rule_zh = str(drill["rule_zh"]).strip()

    ask_turns = [
        ("JF", base_k),
        ("PAUSE", 0.14),
        ("T_VC", ask_zh),
    ]
    teach_turns = [
        ("T_VC", f"你要这样想：{rule_zh}"),
        ("PAUSE", 0.22),
        ("JF", target_k),
        ("PAUSE", 0.24),
        ("JF", chunk_k),
    ]
    model_turns = [("JF", target_k)]
    return {"ask": ask_turns, "teach": teach_turns, "model": model_turns}


def conj_audio_basename(drill_id: str, slot: str) -> str:
    safe = re.sub(r"[^A-Za-z0-9_-]", "", str(drill_id or "")).lower()
    return f"cj_{safe}_{slot}.mp3"


def build_speaking_ask_spoken(sp: dict) -> str:
    """Build a natural, zero-spoiler Mandarin eyes-free sentence-building prompt for any N3/N2 speaking prompt."""
    short = str(sp.get("prompt_short") or sp.get("prompt_zh") or "").strip().strip("。.")
    title = str(sp.get("title") or sp.get("key") or "").strip()
    clean_pat = re.sub(r"^[〜～]+", "", title).strip()
    clean_pat = re.sub(r"[（(][^）)]*[）)]", "", clean_pat).strip()
    if short and clean_pat:
        return f"想表达「{short}」，试着用「{clean_pat}」说一句日语。"
    if short:
        return f"想表达「{short}」，试着用日语说一句。"
    return f"试着用「{clean_pat or title}」造一句日常日语。"


def speaking_ask_hash(text: str) -> str:
    return hashlib.sha256(f"v85spkask:{text}".encode("utf-8")).hexdigest()[:10]
