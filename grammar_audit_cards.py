def build_grammar_audit_spec(item: dict) -> dict:
    """Return clean Jobs × Zen visual + 3-beat audio spec for any grammar audit item (N3 & future N2)."""
    gid = str(item.get("gid") or "").strip()
    name = str(item.get("name") or "").strip()
    raw_meaning = str(item.get("meaning") or "").strip()
    raw_rule = str(item.get("rule") or "").strip()
    ex_ja = str(item.get("ex_ja") or "").strip()

    cur = GA_CARD_CURATION.get(gid)
    if cur:
        meaning, cue, pat_ja, hook_zh, hl = cur
        return {
            "meaning": meaning,
            "cue": cue,
            "pat_ja": pat_ja,
            "hook_zh": hook_zh,
            "hl": list(hl),
        }

    # Safe fallback for future N2 or newly added grammar items
    meaning = re.sub(r"[（(][^）)]*[）)]", "", raw_meaning).replace("—", "，").strip(" ，。；") or raw_meaning
    cue = raw_rule.split("；")[0].replace("—", "，").strip()
    if len(cue) > 36:
        cue = cue[:35].rstrip("，、； ") + "…"
    pat_clean = re.sub(r"[（(][^）)]*[）)]", "", name)
    pat_clean = pat_clean.split("／")[0].split("/")[0].replace("〜", "、").replace("~", "、").strip(" 、。")
    pat_ja = (pat_clean or name).strip(" 。") + "。"
    hook_zh = f"{meaning}。{cue}" if (cue and meaning not in cue) else (cue or meaning)
    hook_zh = hook_zh.replace("—", "，").strip(" ，。") + "。"
    hl_auto = [seg for seg in re.split(r"[〜~/／（）()]+", name) if len(seg) >= 2]
    return {
        "meaning": meaning,
        "cue": cue,
        "pat_ja": pat_ja,
        "hook_zh": hook_zh,
        "hl": hl_auto,
    }

