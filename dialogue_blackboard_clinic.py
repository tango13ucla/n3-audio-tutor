async def _synth_edge_raw(voice: str, rate: str, pitch: str, text: str, out_mp3: str) -> None:
    global _TTS_SEM
    import edge_tts

    if _TTS_SEM is None:
        _TTS_SEM = asyncio.Semaphore(16)
    clean_txt = re.sub(r"[〜～]+", " ", str(text or "")).strip()
    clean_txt = re.sub(r"^[っッ]+", "", clean_txt).strip()
    if not clean_txt or not SPEAKABLE_RE.search(clean_txt):
        raise ValueError(f"Unspeakable segment: {text!r}")
    for attempt in range(4):
        try:
            async with _TTS_SEM:
                comm = edge_tts.Communicate(text=clean_txt, voice=voice, rate=rate, pitch=pitch)
                await asyncio.wait_for(comm.save(out_mp3), timeout=20.0)
            if os.path.exists(out_mp3) and os.path.getsize(out_mp3) > 400:
                return
        except Exception:
            if attempt == 3:
                raise
            await asyncio.sleep(0.5 * (attempt + 1))


def _decode_trimmed_pcm(mp3_path: str, sr: int = 24000, trim_pad_ms: float = 18.0):
    import array
    import math

    cmd = [
        "ffmpeg", "-y", "-v", "error", "-i", mp3_path,
        "-ac", "1", "-ar", str(sr), "-f", "f32le", "pipe:1",
    ]
    res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
    arr = array.array("f")
    arr.frombytes(res.stdout)
    n = len(arr)
    if n == 0:
        return arr
    # Trim leading/trailing silence smoothly
    thresh = 0.012
    first_nz = -1
    for i in range(n):
        v = arr[i]
        if v > thresh or v < -thresh:
            first_nz = i
            break
    if first_nz < 0:
        return arr[: min(n, int(sr * 0.1))]
    last_nz = first_nz
    for i in range(n - 1, first_nz - 1, -1):
        v = arr[i]
        if v > thresh or v < -thresh:
            last_nz = i
            break
    pad = int(sr * (trim_pad_ms / 1000.0))
    lo = max(0, first_nz - pad)
    hi = min(n, last_nz + pad)
    trimmed = arr[lo:hi]
    tn = len(trimmed)
    if tn == 0:
        return trimmed
    # Gentle 6ms edge fade to prevent any click
    fade_n = min(int(sr * 0.006), tn // 4)
    if fade_n > 1:
        denom = float(fade_n - 1)
        for i in range(fade_n):
            r = i / denom
            trimmed[i] *= r
            trimmed[tn - 1 - i] *= r
    # RMS loudness normalization to crisp studio -18 dBFS target
    sq_sum = 0.0
    for i in range(0, tn, 2):
        v = trimmed[i]
        sq_sum += v * v
    rms = math.sqrt((sq_sum / max(1, (tn + 1) // 2)) + 1e-12)
    target_rms = 0.135
    if rms > 1e-4:
        gain = min(2.4, max(0.45, target_rms / rms))
        for i in range(tn):
            val = trimmed[i] * gain
            if val > 0.94:
                val = 0.94
            elif val < -0.94:
                val = -0.94
            trimmed[i] = val
    return trimmed


async def synthesize_single_clinic(
    clinic: dict, sem: asyncio.Semaphore, force: bool = False
) -> dict:
    import array

    sr = 24000
    cid = clinic["id"]
    chash = _clinic_content_hash(clinic)
    out_mp3 = CLINIC_AUDIO_DIR / f"{cid}.mp3"
    rel_url = f"./audio/clinic/{cid}.mp3?v={chash}"

    async with sem:
        tmpdir = tempfile.mkdtemp(prefix=f"clinic_{cid}_")
        try:
            # 1. Synthesize all micro-segments in parallel for this clinic
            tasks = []
            turn_seg_specs: list[list[tuple[str, str, str]]] = []
            seg_idx = 0
            for spk, _step, raw_txt in clinic["turns"]:
                if spk in ("ja_m", "ja_f"):
                    v, r, p = VOICE_CFG[spk]
                    seg_file = os.path.join(tmpdir, f"seg_{seg_idx:03d}.mp3")
                    seg_idx += 1
                    tasks.append(_synth_edge_raw(v, r, p, strip_jp_markers(raw_txt), seg_file))
                    turn_seg_specs.append([(seg_file, "ja", spk)])
                else:
                    zh_v, zh_r, zh_p = VOICE_CFG[spk]
                    jp_key = "ja_f" if spk == "partner" else "ja_m"
                    jp_v, jp_r, jp_p = VOICE_CFG[jp_key]
                    parts = _split_inline_jp(raw_txt)
                    spec_list = []
                    for kind, chunk in parts:
                        seg_file = os.path.join(tmpdir, f"seg_{seg_idx:03d}.mp3")
                        seg_idx += 1
                        if kind == "jp":
                            tasks.append(_synth_edge_raw(jp_v, jp_r, jp_p, chunk, seg_file))
                        else:
                            tasks.append(_synth_edge_raw(zh_v, zh_r, zh_p, chunk, seg_file))
                        spec_list.append((seg_file, kind, spk))
                    turn_seg_specs.append(spec_list)

            await asyncio.gather(*tasks)

            # 2. Stitch turns with exact conversational timing & record sample-accurate cues
            full_pcm = array.array("f")
            cues: list[dict] = []
            lead_n = int(sr * 0.08)
            full_pcm.extend([0.0] * lead_n)

            prev_spk = ""
            for t_idx, (spk, step_idx, raw_txt) in enumerate(clinic["turns"]):
                if t_idx > 0:
                    if spk in ("ja_m", "ja_f"):
                        gap_s = 0.28
                    elif prev_spk in ("ja_m", "ja_f"):
                        gap_s = 0.34
                    elif spk != prev_spk:
                        gap_s = 0.24
                    else:
                        gap_s = 0.16
                    full_pcm.extend([0.0] * int(sr * gap_s))

                turn_start_sec = round(len(full_pcm) / sr, 2)
                cues.append({
                    "t": turn_start_sec,
                    "spk": spk,
                    "label": SPEAKER_LABEL.get(spk, "老师"),
                    "text": strip_jp_markers(raw_txt),
                    "step": int(step_idx),
                })

                segs = turn_seg_specs[t_idx]
                for s_i, (seg_file, kind, _sp) in enumerate(segs):
                    if s_i > 0:
                        # Tight natural code-switch breath (45ms)
                        full_pcm.extend([0.0] * int(sr * 0.045))
                    pad_ms = 12.0 if len(segs) > 1 else 22.0
                    pcm = _decode_trimmed_pcm(seg_file, sr=sr, trim_pad_ms=pad_ms)
                    full_pcm.extend(pcm)
                prev_spk = spk

            full_pcm.extend([0.0] * int(sr * 0.22))
            total_dur = round(len(full_pcm) / sr, 1)

            # 3. Encode compact studio MP3 (48kbps mono 24kHz -> ~150-240KB per 30-45s dialogue)
            CLINIC_AUDIO_DIR.mkdir(parents=True, exist_ok=True)
            tmp_mp3 = os.path.join(tmpdir, f"{cid}.mp3")
            cmd = [
                "ffmpeg", "-y", "-v", "error",
                "-f", "f32le", "-ar", str(sr), "-ac", "1", "-i", "pipe:0",
                "-c:a", "libmp3lame", "-b:a", "48k", "-ar", "24000", "-ac", "1",
                tmp_mp3,
            ]
            subprocess.run(cmd, input=full_pcm.tobytes(), check=True)
            shutil.move(tmp_mp3, str(out_mp3))

            return {
                "audio": rel_url,
                "hash": chash,
                "duration": total_dur,
                "cues": cues,
            }
        finally:
            shutil.rmtree(tmpdir, ignore_errors=True)


async def generate_all_clinic_audio(force: bool = False) -> dict:
    """Synthesize any missing/changed clinic MP3s and persist to audio/audio_manifest.json."""
    manifest = {}
    if MANIFEST_PATH.exists():
        manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    existing = dict(manifest.get("dialogue_clinics") or {})
    sem = asyncio.Semaphore(6)

    to_run = []
    for c in ALL_CLINICS:
        cid = c["id"]
        chash = _clinic_content_hash(c)
        mp3_path = CLINIC_AUDIO_DIR / f"{cid}.mp3"
        prev = existing.get(cid) or {}
        if (
            not force
            and mp3_path.exists()
            and mp3_path.stat().st_size > 8000
            and prev.get("hash") == chash
            and prev.get("cues")
        ):
            continue
        to_run.append(c)

    if to_run:
        print(f"[clinic-tts] Synthesizing {len(to_run)}/{len(ALL_CLINICS)} living-blackboard dialogues...", flush=True)

        async def _run_one(c_item: dict):
            meta = await synthesize_single_clinic(c_item, sem, force=force)
            return c_item, meta

        futs = [asyncio.create_task(_run_one(c)) for c in to_run]
        for fut in asyncio.as_completed(futs):
            c, meta = await fut
            existing[c["id"]] = meta
            manifest["dialogue_clinics"] = existing
            MANIFEST_PATH.write_text(
                json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
            )
            print(f"  [ok] {c['id']} ({c['title']}): {meta['duration']}s, {len(meta['cues'])} cues -> {meta['audio']}", flush=True)
    else:
        print(f"[clinic-tts] All {len(ALL_CLINICS)} living-blackboard clinic MP3s up-to-date.", flush=True)

    manifest["dialogue_clinics"] = existing
    MANIFEST_PATH.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return existing


def _allowed_packs_for_mod(mod_str: str) -> list[str]:
    m = str(mod_str or "").strip().lower()
    if m in ("listening", "聴解", "听力"):
        return ["listening"]
    if m in ("vocab", "語彙", "词汇"):
        return ["leech", "confusion"]
    # grammar / henkei / 活用 / 文法 / 语法 -> NEVER cross-leak into listening!
    return ["confusion", "leech"]


def match_clinic_strict(id_tokens: list[str], head_text: str, mod_str: str) -> dict | None:
    """
    Canonical v93 zero-false-positive clinic matcher (mirrored identically in JS):
    1. Strict pack isolation (grammar/henkei/vocab NEVER leak into listening; listening ONLY matches listening).
    2. Pass 1 (Highest priority): exact token membership in `match_ids` (ZERO substring matching!).
    3. Pass 2: term match ONLY against normalized head_text (NEVER Chinese sub-meanings or unrelated examples),
       strictly respecting `exclude_terms`.
    4. Pass 3: ZERO blind catch-all fallback (returns None if nothing genuinely matches).
    """
    packs = _allowed_packs_for_mod(mod_str)
    tok_set = {str(t).strip() for t in (id_tokens or []) if str(t or "").strip()}
    head_norm = str(head_text or "").replace("~", "〜").replace("～", "〜").strip()

    # Pass 1: exact ID match across allowed packs in priority order
    if tok_set:
        for pk in packs:
            for c in ALL_CLINICS:
                if c.get("pack") != pk:
                    continue
                mids = c.get("match_ids") or []
                if any(tid in mids for tid in tok_set):
                    return c

    # Pass 2: strict head-term match with explicit exclusions
    if head_norm:
        for pk in packs:
            for c in ALL_CLINICS:
                if c.get("pack") != pk:
                    continue
                excls = [str(e).replace("~", "〜").replace("～", "〜") for e in (c.get("exclude_terms") or []) if e]
                if any(ex in head_norm for ex in excls):
                    continue
                mterms = [str(t).replace("~", "〜").replace("～", "〜") for t in (c.get("match_terms") or []) if t]
                if any(mt in head_norm for mt in mterms):
                    return c

    return None


