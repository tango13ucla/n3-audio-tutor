SPEAKABLE_RE = re.compile(r"[0-9A-Za-z\u3040-\u30ff\u4e00-\u9fff]")
AUTO_JP_SPAN_RE = re.compile(
    r"(?:[0-9０-９\u4e00-\u9fff]{0,4}[\u3041-\u3096\u30a1-\u30faー]+(?:[\u4e00-\u9fff\u3041-\u3096\u30a1-\u30faー]*[\u3041-\u3096\u30a1-\u30faー])?)"
)
_TTS_SEM: asyncio.Semaphore | None = None


def _split_zh_auto_jp(seg: str) -> list[tuple[str, str]]:
    """Split any residual Japanese kana spans (including kanji+kana words in 「」) out of Mandarin text."""
    # First split quoted Japanese words like 「凪ぐ」「必ずしも」「1日おき」「降らない」
    out: list[tuple[str, str]] = []
    pos = 0
    quote_jp = re.compile(r"「([^」]*[\u3041-\u3096\u30a1-\u30fa][^」]*)」")
    for m in quote_jp.finditer(seg):
        before = seg[pos : m.start()]
        if before:
            out.extend(_split_plain_kana(before))
        inner = m.group(1).strip()
        # If inner mixes Chinese gloss like 「あまり不太…」, split by kana boundary
        if re.search(r"[\u4e00-\u9fff]{2,}", inner) and not re.match(r"^[0-9\u4e00-\u9fff]{1,3}[\u3041-\u3096\u30a1-\u30fa]", inner):
            out.extend(_split_plain_kana(inner))
        else:
            jp_clean = re.sub(r"[〜～]+", " ", inner).strip(" \t\r\n、，。！？「」『』（）")
            if jp_clean and SPEAKABLE_RE.search(jp_clean):
                out.append(("jp", jp_clean))
        pos = m.end()
    if pos < len(seg):
        out.extend(_split_plain_kana(seg[pos:]))
    return out


def _split_plain_kana(txt: str) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    pos = 0
    kana_re = re.compile(r"[\u3041-\u3096\u30a1-\u30faー]+")
    for m in kana_re.finditer(txt):
        if m.start() > pos:
            z = txt[pos : m.start()].strip(" \t\r\n、，。！？「」『』（）")
            if z and SPEAKABLE_RE.search(z):
                out.append(("zh", z))
        k = m.group(0).strip()
        if k and SPEAKABLE_RE.search(k):
            out.append(("jp", k))
        pos = m.end()
    if pos < len(txt):
        z = txt[pos:].strip(" \t\r\n、，。！？「」『』（）")
        if z and SPEAKABLE_RE.search(z):
            out.append(("zh", z))
    return out


def _split_inline_jp(text: str) -> list[tuple[str, str]]:
    """Split a Mandarin turn with {{jp:...}} markers into speakable [('zh', ...), ('jp', ...)] chunks with 0% bare kana in zh."""
    out: list[tuple[str, str]] = []
    pos = 0
    for m in JP_INLINE_RE.finditer(text):
        if m.start() > pos:
            out.extend(_split_zh_auto_jp(text[pos : m.start()]))
        jp = re.sub(r"[〜～]+", " ", m.group(1)).strip(" \t\r\n、，。！？「」『』（）")
        if jp and SPEAKABLE_RE.search(jp):
            out.append(("jp", jp))
        pos = m.end()
    if pos < len(text):
        out.extend(_split_zh_auto_jp(text[pos:]))
    return out


